func validateOpaqueGeneratedInterfaces(sources map[string][]byte) error {
	for _, source := range sources {
		for _, line := range strings.Split(string(source), "\n") {
			fields := strings.Fields(line)
			if len(fields) != 3 || fields[0] != "type" || fields[2] != "interface{}" {
				continue
			}
			if _, allowed := opaqueGeneratedInterfaceAllowlist[fields[1]]; !allowed {
				return fmt.Errorf("generated type %s is an unreviewed interface{}; add typed generation or an explicit opaque allowlist entry", fields[1])
			}
		}
	}
	return nil
}

func sanitizedFallbackTarget(name string, generated map[string]struct{}) (string, bool) {
	target := "Sanitized" + name + "JSON"
	if _, ok := generated[target]; ok {
		return target, true
	}
	return "", false
}

func collectGeneratedTypes(sources map[string][]byte) map[string]struct{} {
	generated := map[string]struct{}{}
	for _, src := range sources {
		lines := strings.Split(string(src), "\n")
		for _, line := range lines {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "type ") {
				fields := strings.Fields(line)
				if len(fields) >= 2 {
					generated[fields[1]] = struct{}{}
				}
			}
		}
	}
	return generated
}

