func main() {
	sdkRoot, err := repoRoot()
	if err != nil {
		fatal(err)
	}
	codexRoot, err := codexRepoRoot(sdkRoot)
	if err != nil {
		fatal(err)
	}

	tempDir, err := os.MkdirTemp("", "codex-schema-go-sdk-")
	if err != nil {
		fatal(err)
	}
	defer func() {
		_ = os.RemoveAll(tempDir)
	}()

	schemaDir := filepath.Join(tempDir, "schemas")
	if err := os.MkdirAll(schemaDir, 0o755); err != nil {
		fatal(err)
	}

	codexSourceRoot, cleanupCodexSource, err := codexSourceForGeneration(codexRoot, tempDir)
	if err != nil {
		fatal(err)
	}
	defer cleanupCodexSource()

	codexCommit, err := codexCommitHash(codexSourceRoot)
	if err != nil {
		fatal(err)
	}

	codexVersion, err := codexPackageVersion(codexSourceRoot)
	if err != nil {
		fatal(err)
	}

	if err := exportSchemas(codexSourceRoot, schemaDir); err != nil {
		fatal(err)
	}
	if err := validateUnionInventory(schemaDir); err != nil {
		fatal(err)
	}
	if _, err := collectDiscriminatedUnions(schemaDir, true); err != nil {
		fatal(err)
	}
	if err := generateProtocolTypes(schemaDir, sdkRoot, codexCommit, codexVersion); err != nil {
		fatal(err)
	}

	if err := generateRPCStubs(schemaDir, sdkRoot, codexCommit); err != nil {
		fatal(err)
	}
}

func exportSchemas(codexRoot, outDir string) error {
	cmd := exec.Command("cargo", "run", "-p", "codex-app-server-protocol", "--bin", "export", "--", "--out", outDir)
	cmd.Dir = filepath.Join(codexRoot, "codex-rs")
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func generateProtocolTypes(schemaDir, repoRoot, codexCommit, codexVersion string) error {
	cfg := generator.Config{
		DefaultPackageName: "protocol",
		DefaultOutputName:  "types_gen.go",
		Tags:               []string{"json"},
		Capitalizations:    []string{"ID", "JSON", "RPC", "MCP", "OAuth", "HTTP", "URL", "SSE", "UUID"},
		OnlyModels:         true,
	}
	gen, err := generator.New(cfg)
	if err != nil {
		return err
	}

	schemaFiles, err := findSchemaFiles(schemaDir)
	if err != nil {
		return err
	}

	skip := skipSchemaFiles()
	var fallbacks []string
	var titles []string
	for _, file := range schemaFiles {
		if filepath.Base(file) == schemaBundleFile {
			continue
		}
		if skip[filepath.Base(file)] {
			continue
		}
		title, titleErr := schemaTitle(file)
		if titleErr != nil {
			return titleErr
		}
		if title != "" {
			titles = append(titles, title)
		}
		if err := safeDoFile(gen, file); err != nil {
			if title == "" {
				return fmt.Errorf("generate types from %s: %w", file, err)
			}
			fallbacks = append(fallbacks, title)
		}
	}

	sources, err := gen.Sources()
	if err != nil {
		return err
	}

	unions, err := collectDiscriminatedUnions(schemaDir, false)
	if err != nil {
		return err
	}
	manualTypes := manualProtocolTypes()
	if err := validateManualStructSchemaCoverage(schemaDir, repoRoot); err != nil {
		return err
	}
	for name := range unions {
		manualTypes[name] = struct{}{}
	}
	for name, src := range sources {
		sources[name] = filterManualTypeDeclarations(src, manualTypes)
	}
	if err := validateOpaqueGeneratedInterfaces(sources); err != nil {
		return err
	}

	outDir := filepath.Join(repoRoot, "protocol")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	generated := collectGeneratedTypes(sources)
	for name := range manualTypes {
		generated[name] = struct{}{}
	}
	for _, title := range titles {
		if title == "" {
			continue
		}
		if _, ok := generated[title]; ok {
			continue
		}
		if _, ok := generated[title+"JSON"]; ok {
			continue
		}
		fallbacks = append(fallbacks, title)
	}
	deprecatedSanitized := make(map[string]string)
	for _, name := range fallbacks {
		if target, ok := sanitizedFallbackTarget(name, generated); ok {
			deprecatedSanitized[target] = name
		}
	}

	for name, src := range sources {
		normalized := normalizeGeneratedHeader(src, codexCommit)
		normalized = deprecateSanitizedFallbacks(normalized, deprecatedSanitized)
		if err := writeProtocolGoFile(outDir, name, normalized); err != nil {
			return err
		}
	}

	if err := writeFallbackTypes(outDir, fallbacks, generated, codexCommit); err != nil {
		return err
	}

	if err := writeProtocolAliases(outDir, generated, fallbacks, codexCommit); err != nil {
		return err
	}
	compatibilityTypes := make(map[string]struct{}, len(generated)+len(fallbacks))
	for name := range generated {
		compatibilityTypes[name] = struct{}{}
	}
	for _, name := range fallbacks {
		compatibilityTypes[name] = struct{}{}
	}
	for name := range protocolAliasNames(generated, fallbacks) {
		compatibilityTypes[name] = struct{}{}
	}
	if err := writeCompatibilityAliases(outDir, compatibilityTypes, codexCommit); err != nil {
		return err
	}

	if err := writeProtocolMetadata(outDir, codexCommit, codexVersion); err != nil {
		return err
	}

	unionSource := renderDiscriminatedUnionTypes(unions, codexCommit)
	unionPath := filepath.Join(outDir, "unions_gen.go")
	if len(unionSource) == 0 {
		_ = os.Remove(unionPath)
	} else if err := writeProtocolGoFile(outDir, filepath.Base(unionPath), unionSource); err != nil {
		return err
	}

	return nil
}

