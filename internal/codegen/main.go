func buildRPCMethods(methods []rpcMethod, defs map[string]struct{}, overrides map[string]string) ([]rpcMethod, error) {
	resolved := make([]rpcMethod, 0, len(methods))
	for _, method := range methods {
		responseType, err := resolveResponseType(method, defs, overrides)
		if err != nil {
			return nil, err
		}
		method.ResponseType = responseType
		resolved = append(resolved, method)
	}
	return resolved, nil
}

func resolveResponseType(method rpcMethod, defs map[string]struct{}, overrides map[string]string) (string, error) {
	if overrides != nil {
		if override, ok := overrides[method.Method]; ok {
			return override, nil
		}
	}

	if method.ParamsType != "" {
		base := strings.TrimSuffix(method.ParamsType, "Params")
		candidate := base + "Response"
		if _, ok := defs[candidate]; ok {
			return candidate, nil
		}
	}

	candidate := methodBaseName(method.Method) + "Response"
	if _, ok := defs[candidate]; ok {
		return candidate, nil
	}

	return "", fmt.Errorf("unable to resolve response type for method %q", method.Method)
}

func rawMethodBaseName(method string) string {
	parts := strings.FieldsFunc(method, func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9')
	})
	var b strings.Builder
	for _, part := range parts {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]))
		if len(part) > 1 {
			b.WriteString(part[1:])
		}
	}
	return b.String()
}

var canonicalInitialisms = map[string]string{
	"http":  "HTTP",
	"id":    "ID",
	"json":  "JSON",
	"mcp":   "MCP",
	"oauth": "OAuth",
	"rpc":   "RPC",
	"sse":   "SSE",
	"url":   "URL",
	"uuid":  "UUID",
}

func canonicalGoName(name string) string {
	words := splitGoName(name)
	for index, word := range words {
		if initialism, ok := canonicalInitialisms[strings.ToLower(word)]; ok {
			words[index] = initialism
		}
	}
	return strings.Join(words, "")
}

func legacyGoName(name string) string {
	replacer := strings.NewReplacer("MCP", "Mcp", "OAuth", "Oauth")
	return replacer.Replace(name)
}

func splitGoName(name string) []string {
	runes := []rune(name)
	if len(runes) == 0 {
		return nil
	}
	var words []string
	start := 0
	for index := 1; index < len(runes); index++ {
		previous := runes[index-1]
		current := runes[index]
		nextLower := index+1 < len(runes) && unicode.IsLower(runes[index+1])
		boundary := unicode.IsLower(previous) && unicode.IsUpper(current) ||
			unicode.IsUpper(previous) && unicode.IsUpper(current) && nextLower ||
			unicode.IsDigit(previous) != unicode.IsDigit(current)
		if boundary {
			words = append(words, string(runes[start:index]))
			start = index
		}
	}
	return append(words, string(runes[start:]))
}

func methodBaseName(method string) string {
	return canonicalGoName(rawMethodBaseName(method))
}

