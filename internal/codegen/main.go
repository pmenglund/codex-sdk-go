func findSchemaFiles(schemaDir string) ([]string, error) {
	var files []string
	err := filepath.WalkDir(schemaDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if filepath.Ext(path) != ".json" {
			return nil
		}
		files = append(files, path)
		return nil
	})
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	return files, nil
}

func validateUnionInventory(schemaDir string) error {
	files, err := findSchemaFiles(schemaDir)
	if err != nil {
		return err
	}
	unique := make(map[string]struct{})
	for _, file := range files {
		data, readErr := os.ReadFile(file)
		if readErr != nil {
			return readErr
		}
		var node any
		if err := json.Unmarshal(data, &node); err != nil {
			return fmt.Errorf("decode union inventory from %s: %w", file, err)
		}
		collectUnionSchemas(node, unique)
	}
	items := make([]string, 0, len(unique))
	for item := range unique {
		items = append(items, item)
	}
	sort.Strings(items)
	digest := fmt.Sprintf("%x", sha256.Sum256([]byte(strings.Join(items, "\n"))))
	if os.Getenv("CODEX_PRINT_UNION_INVENTORY") == "1" {
		fmt.Fprintf(os.Stderr, "union inventory sha256 %s (%d unique schemas)\n", digest, len(items))
		for _, item := range items {
			fmt.Fprintf(os.Stderr, "%x  %s\n", sha256.Sum256([]byte(item)), item)
		}
	}
	if digest != approvedUnionInventorySHA256 {
		return fmt.Errorf("schema union inventory changed: got sha256 %s across %d unique union schemas; rerun with CODEX_PRINT_UNION_INVENTORY=1, review every new or changed oneOf/anyOf, then update approvedUnionInventorySHA256", digest, len(items))
	}
	return nil
}

func collectUnionSchemas(node any, unique map[string]struct{}) {
	switch value := node.(type) {
	case map[string]any:
		if _, hasOneOf := value["oneOf"]; hasOneOf {
			if data, err := json.Marshal(value); err == nil {
				unique[string(data)] = struct{}{}
			}
		}
		if _, hasAnyOf := value["anyOf"]; hasAnyOf {
			if data, err := json.Marshal(value); err == nil {
				unique[string(data)] = struct{}{}
			}
		}
		for _, child := range value {
			collectUnionSchemas(child, unique)
		}
	case []any:
		for _, child := range value {
			collectUnionSchemas(child, unique)
		}
	}
}

func safeDoFile(gen *generator.Generator, file string) (err error) {
	sanitized, cleanup, err := sanitizeSchemaFile(file)
	if err != nil {
		return err
	}
	defer cleanup()
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("panic: %v", r)
		}
	}()
	return gen.DoFile(sanitized)
}

func sanitizeSchemaFile(path string) (string, func(), error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", nil, err
	}
	var node any
	if err := json.Unmarshal(data, &node); err != nil {
		return "", nil, err
	}
	stripSubschemas(node)
	out, err := json.Marshal(node)
	if err != nil {
		return "", nil, err
	}
	sanitizedName := "sanitized-" + filepath.Base(path)
	sanitizedPath := filepath.Join(filepath.Dir(path), sanitizedName)
	if err := os.WriteFile(sanitizedPath, out, 0o644); err != nil {
		return "", nil, err
	}
	cleanup := func() {
		_ = os.Remove(sanitizedPath)
	}
	return sanitizedPath, cleanup, nil
}

func stripSubschemas(node any) {
	switch value := node.(type) {
	case map[string]any:
		delete(value, "oneOf")
		delete(value, "anyOf")
		for _, child := range value {
			stripSubschemas(child)
		}
	case []any:
		for _, child := range value {
			stripSubschemas(child)
		}
	}
}

func repoRoot() (string, error) {
	cwd, err := os.Getwd()
	if err != nil {
		return "", err
	}

	// Walk up until we find this repository root.
	current := cwd
	for {
		if exists(filepath.Join(current, "go.mod")) && exists(filepath.Join(current, "internal", "codegen", "main.go")) {
			return current, nil
		}
		parent := filepath.Dir(current)
		if parent == current {
			break
		}
		current = parent
	}

	return "", fmt.Errorf("unable to locate codex-sdk-go repo root from %s", cwd)
}

func codexRepoRoot(sdkRoot string) (string, error) {
	if configured := strings.TrimSpace(os.Getenv(codexRepoRootEnv)); configured != "" {
		root := configured
		if !filepath.IsAbs(root) {
			root = filepath.Join(sdkRoot, root)
		}
		if !exists(filepath.Join(root, "codex-rs")) {
			return "", fmt.Errorf("%s=%q does not contain codex-rs", codexRepoRootEnv, configured)
		}
		return root, nil
	}

	defaultRoot := filepath.Join(sdkRoot, "..", "codex")
	if exists(filepath.Join(defaultRoot, "codex-rs")) {
		return defaultRoot, nil
	}

	return "", fmt.Errorf("could not find codex checkout at %s (set %s)", defaultRoot, codexRepoRootEnv)
}

func codexSourceForGeneration(codexRoot, tempDir string) (string, func(), error) {
	ref := strings.TrimSpace(os.Getenv(codexRepoRefEnv))
	if ref == "" {
		return codexRoot, func() {}, nil
	}

	worktreeDir := filepath.Join(tempDir, "codex-source")
	if err := addCodexWorktree(codexRoot, worktreeDir, ref); err != nil {
		return "", nil, err
	}

	cleanup := func() {
		if err := removeCodexWorktree(codexRoot, worktreeDir); err != nil {
			fmt.Fprintf(os.Stderr, "warning: remove codex worktree: %v\n", err)
		}
	}

	if !exists(filepath.Join(worktreeDir, "codex-rs")) {
		cleanup()
		return "", nil, fmt.Errorf("%s=%q does not contain codex-rs", codexRepoRefEnv, ref)
	}

	return worktreeDir, cleanup, nil
}

func addCodexWorktree(codexRoot, worktreeDir, ref string) error {
	out, err := gitCombinedOutput("-C", codexRoot, "worktree", "add", "--detach", worktreeDir, ref)
	if err != nil {
		return gitCommandError("create codex worktree", out, err)
	}
	return nil
}

func removeCodexWorktree(codexRoot, worktreeDir string) error {
	out, err := gitCombinedOutput("-C", codexRoot, "worktree", "remove", "--force", worktreeDir)
	if err != nil {
		return gitCommandError("remove codex worktree", out, err)
	}
	return nil
}

func codexCommitHash(codexRoot string) (string, error) {
	out, err := gitCombinedOutput("-C", codexRoot, "rev-parse", "HEAD")
	if err != nil {
		return "", gitCommandError("resolve codex commit hash", out, err)
	}
	hash := strings.TrimSpace(string(out))
	if hash == "" {
		return "", fmt.Errorf("resolve codex commit hash: empty hash")
	}
	return hash, nil
}

func codexPackageVersion(codexRoot string) (string, error) {
	data, err := os.ReadFile(filepath.Join(codexRoot, "codex-rs", "Cargo.toml"))
	if err != nil {
		return "", fmt.Errorf("read codex Cargo.toml: %w", err)
	}
	version := parseWorkspacePackageVersion(string(data))
	if version == "" {
		return "", errors.New("resolve codex package version: [workspace.package] version not found")
	}
	return version, nil
}

func parseWorkspacePackageVersion(contents string) string {
	inWorkspacePackage := false
	for _, line := range strings.Split(contents, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if strings.HasPrefix(line, "[") {
			inWorkspacePackage = line == "[workspace.package]"
			continue
		}
		if !inWorkspacePackage || !strings.HasPrefix(line, "version") {
			continue
		}
		parts := strings.SplitN(line, "=", 2)
		if len(parts) != 2 || strings.TrimSpace(parts[0]) != "version" {
			continue
		}
		return strings.Trim(strings.TrimSpace(parts[1]), `"'`)
	}
	return ""
}

func gitCommandError(action string, out []byte, err error) error {
	msg := strings.TrimSpace(string(out))
	if msg == "" {
		return fmt.Errorf("%s: %w", action, err)
	}
	return fmt.Errorf("%s: %s", action, msg)
}

var gitCombinedOutput = func(args ...string) ([]byte, error) {
	cmd := exec.Command("git", args...)
	return cmd.CombinedOutput()
}

func exists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
