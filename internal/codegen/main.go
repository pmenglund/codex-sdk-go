func main() {
	sdkRoot, err := repoRoot()
	if err != nil {
		fatal(err)
	}
	codexRoot, err := codexRepoRoot(sdkRoot)
	if err != nil {
		fatal(err)
	}

	tempDir, err := os.MkdirTemp("", "codex-schema-go-sdk-")
	if err != nil {
		fatal(err)
	}
	defer func() {
		_ = os.RemoveAll(tempDir)
	}()

	schemaDir := filepath.Join(tempDir, "schemas")
	if err := os.MkdirAll(schemaDir, 0o755); err != nil {
		fatal(err)
	}

	codexSourceRoot, cleanupCodexSource, err := codexSourceForGeneration(codexRoot, tempDir)
	if err != nil {
		fatal(err)
	}
	defer cleanupCodexSource()

	codexCommit, err := codexCommitHash(codexSourceRoot)
	if err != nil {
		fatal(err)
	}

	codexVersion, err := codexPackageVersion(codexSourceRoot)
	if err != nil {
		fatal(err)
	}

	if err := exportSchemas(codexSourceRoot, schemaDir); err != nil {
		fatal(err)
	}
	if err := validateUnionInventory(schemaDir); err != nil {
		fatal(err)
	}
	if _, err := collectDiscriminatedUnions(schemaDir, true); err != nil {
		fatal(err)
	}
	if err := generateProtocolTypes(schemaDir, sdkRoot, codexCommit, codexVersion); err != nil {
		fatal(err)
	}

	if err := generateRPCStubs(schemaDir, sdkRoot, codexCommit); err != nil {
		fatal(err)
	}
}

func exportSchemas(codexRoot, outDir string) error {
	cmd := exec.Command("cargo", "run", "-p", "codex-app-server-protocol", "--bin", "export", "--", "--out", outDir)
	cmd.Dir = filepath.Join(codexRoot, "codex-rs")
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}

func generateProtocolTypes(schemaDir, repoRoot, codexCommit, codexVersion string) error {
	cfg := generator.Config{
		DefaultPackageName: "protocol",
		DefaultOutputName:  "types_gen.go",
		Tags:               []string{"json"},
		Capitalizations:    []string{"ID", "JSON", "RPC", "MCP", "HTTP", "URL", "SSE", "UUID"},
		OnlyModels:         true,
	}
	gen, err := generator.New(cfg)
	if err != nil {
		return err
	}

	schemaFiles, err := findSchemaFiles(schemaDir)
	if err != nil {
		return err
	}

	skip := skipSchemaFiles()
	var fallbacks []string
	var titles []string
	for _, file := range schemaFiles {
		if filepath.Base(file) == schemaBundleFile {
			continue
		}
		if skip[filepath.Base(file)] {
			continue
		}
		title, titleErr := schemaTitle(file)
		if titleErr != nil {
			return titleErr
		}
		if title != "" {
			titles = append(titles, title)
		}
		if err := safeDoFile(gen, file); err != nil {
			if title == "" {
				return fmt.Errorf("generate types from %s: %w", file, err)
			}
			fallbacks = append(fallbacks, title)
		}
	}

	sources, err := gen.Sources()
	if err != nil {
		return err
	}

	unions, err := collectDiscriminatedUnions(schemaDir, false)
	if err != nil {
		return err
	}
	manualTypes := manualProtocolTypes()
	for name := range unions {
		manualTypes[name] = struct{}{}
	}
	for name, src := range sources {
		sources[name] = filterManualTypeDeclarations(src, manualTypes)
	}
	if err := validateOpaqueGeneratedInterfaces(sources); err != nil {
		return err
	}

	outDir := filepath.Join(repoRoot, "protocol")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	generated := collectGeneratedTypes(sources)
	for name := range manualTypes {
		generated[name] = struct{}{}
	}
	for _, title := range titles {
		if title == "" {
			continue
		}
		if _, ok := generated[title]; ok {
			continue
		}
		if _, ok := generated[title+"JSON"]; ok {
			continue
		}
		fallbacks = append(fallbacks, title)
	}

	for name, src := range sources {
		normalized := normalizeGeneratedHeader(src, codexCommit)
		if err := writeGoFile(outDir, name, normalized); err != nil {
			return err
		}
	}

	if err := writeFallbackTypes(outDir, fallbacks, generated, codexCommit); err != nil {
		return err
	}

	if err := writeProtocolAliases(outDir, generated, fallbacks, codexCommit); err != nil {
		return err
	}

	if err := writeProtocolMetadata(outDir, codexCommit, codexVersion); err != nil {
		return err
	}

	unionSource := renderDiscriminatedUnionTypes(unions, codexCommit)
	unionPath := filepath.Join(outDir, "unions_gen.go")
	if len(unionSource) == 0 {
		_ = os.Remove(unionPath)
	} else if err := writeGoFile(outDir, filepath.Base(unionPath), unionSource); err != nil {
		return err
	}

	return nil
}

func filterManualTypeDeclarations(src []byte, manualTypes map[string]struct{}) []byte {
	lines := strings.SplitAfter(string(src), "\n")
	out := make([]string, 0, len(lines))
	for i := 0; i < len(lines); {
		line := lines[i]
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "type ") {
			fields := strings.Fields(trimmed)
			if len(fields) >= 2 {
				if _, ok := manualTypes[fields[1]]; ok {
					i++
					balance := strings.Count(line, "{") - strings.Count(line, "}")
					for i < len(lines) && balance > 0 {
						balance += strings.Count(lines[i], "{") - strings.Count(lines[i], "}")
						i++
					}
					continue
				}
			}
		}
		out = append(out, line)
		i++
	}
	return []byte(strings.Join(out, ""))
}

type schemaVariant struct {
	Properties map[string]schemaProperty `json:"properties"`
}

type schemaProperty struct {
	Enum  []string `json:"enum"`
	Ref   string   `json:"$ref"`
	Type  string   `json:"type"`
	Items *struct {
		Ref string `json:"$ref"`
	} `json:"items"`
}

type oneOfSchema struct {
	OneOf []schemaVariant `json:"oneOf"`
}

var requiredDiscriminatedUnions = map[string]struct{}{
	"ResponseItem":  {},
	"SandboxPolicy": {},
	"ThreadStatus":  {},
	"UserInput":     {},
}

// opaqueDiscriminatedUnionAllowlist preserves legacy interface-based API types
// whose wire variants are selected by server-request context rather than a
// stable payload discriminator available to SDK callers. New entries require
// review and a generator test.
var opaqueDiscriminatedUnionAllowlist = map[string]struct{}{
	"McpServerElicitationRequestParams": {},
}

type discriminatedUnionSchema struct {
	OneOf []struct {
		Properties map[string]json.RawMessage `json:"properties"`
		Required   []string                   `json:"required"`
	} `json:"oneOf"`
}

type discriminatedUnion struct {
	Name          string
	Discriminator string
	Kinds         []string
	Required      map[string][]string
}

func collectDiscriminatedUnions(schemaDir string, requireCore bool) (map[string]discriminatedUnion, error) {
	files, err := findSchemaFiles(schemaDir)
	if err != nil {
		return nil, err
	}
	found := make(map[string]discriminatedUnion)
	for _, file := range files {
		data, readErr := os.ReadFile(file)
		if readErr != nil {
			return nil, readErr
		}
		var doc struct {
			Title       string                     `json:"title"`
			OneOf       json.RawMessage            `json:"oneOf"`
			Definitions map[string]json.RawMessage `json:"definitions"`
		}
		if json.Unmarshal(data, &doc) != nil {
			continue
		}
		for name, raw := range doc.Definitions {
			if _, opaque := opaqueDiscriminatedUnionAllowlist[name]; opaque {
				continue
			}
			union, ok, unionErr := parseDiscriminatedUnion(name, raw)
			if unionErr != nil {
				return nil, fmt.Errorf("decode discriminated union %s from %s: %w", name, file, unionErr)
			}
			if ok {
				found[name] = union
			}
		}
		if doc.Title != "" && len(doc.OneOf) > 0 {
			if _, opaque := opaqueDiscriminatedUnionAllowlist[doc.Title]; opaque {
				continue
			}
			union, ok, unionErr := parseDiscriminatedUnion(doc.Title, data)
			if unionErr != nil {
				return nil, fmt.Errorf("decode discriminated union %s from %s: %w", doc.Title, file, unionErr)
			}
			if ok {
				found[doc.Title] = union
			}
		}
	}
	if !requireCore {
		return found, nil
	}
	for name := range requiredDiscriminatedUnions {
		if _, ok := found[name]; !ok {
			return nil, fmt.Errorf("required discriminated union %s is missing or unsupported", name)
		}
	}
	return found, nil
}

func parseDiscriminatedUnion(name string, data []byte) (discriminatedUnion, bool, error) {
	var schema discriminatedUnionSchema
	if err := json.Unmarshal(data, &schema); err != nil {
		return discriminatedUnion{}, false, err
	}
	if len(schema.OneOf) < 2 {
		return discriminatedUnion{}, false, nil
	}

	candidates := make(map[string][]string)
	for index, variant := range schema.OneOf {
		variantEnums := make(map[string]string)
		for propertyName, rawProperty := range variant.Properties {
			var property struct {
				Enum []string `json:"enum"`
			}
			if json.Unmarshal(rawProperty, &property) == nil && len(property.Enum) == 1 && property.Enum[0] != "" {
				variantEnums[propertyName] = property.Enum[0]
			}
		}
		if index == 0 {
			for propertyName, value := range variantEnums {
				candidates[propertyName] = []string{value}
			}
			continue
		}
		for propertyName, values := range candidates {
			value, ok := variantEnums[propertyName]
			if !ok {
				delete(candidates, propertyName)
				continue
			}
			candidates[propertyName] = append(values, value)
		}
	}
	if len(candidates) == 0 {
		return discriminatedUnion{}, false, nil
	}
	discriminator := "type"
	if _, ok := candidates[discriminator]; !ok {
		names := make([]string, 0, len(candidates))
		for candidate := range candidates {
			names = append(names, candidate)
		}
		sort.Strings(names)
		discriminator = names[0]
	}
	kinds := candidates[discriminator]
	required := make(map[string][]string, len(kinds))
	seen := make(map[string]struct{}, len(kinds))
	for _, kind := range kinds {
		if _, duplicate := seen[kind]; duplicate {
			return discriminatedUnion{}, false, fmt.Errorf("repeated %s discriminator %q", discriminator, kind)
		}
		seen[kind] = struct{}{}
	}
	for _, variant := range schema.OneOf {
		var discriminatorProperty struct {
			Enum []string `json:"enum"`
		}
		if json.Unmarshal(variant.Properties[discriminator], &discriminatorProperty) != nil || len(discriminatorProperty.Enum) != 1 {
			continue
		}
		fields := append([]string(nil), variant.Required...)
		sort.Strings(fields)
		required[discriminatorProperty.Enum[0]] = fields
	}
	sort.Strings(kinds)
	return discriminatedUnion{Name: name, Discriminator: discriminator, Kinds: kinds, Required: required}, true, nil
}

func renderDiscriminatedUnionTypes(unions map[string]discriminatedUnion, codexCommit string) []byte {
	if len(unions) == 0 {
		return nil
	}
	var b strings.Builder
	b.WriteString(generatedHeader(codexCommit))
	b.WriteString("package protocol\n\n")
	b.WriteString("import (\n\t\"encoding/json\"\n\t\"fmt\"\n)\n\n")
	b.WriteString("func decodeDiscriminatedUnion(data []byte, discriminator string) (string, json.RawMessage, error) {\n")
	b.WriteString("\tif string(data) == \"null\" { return \"\", nil, nil }\n")
	b.WriteString("\tvar object map[string]json.RawMessage\n\tif err := json.Unmarshal(data, &object); err != nil { return \"\", nil, err }\n")
	b.WriteString("\trawKind, ok := object[discriminator]; if !ok { return \"\", nil, fmt.Errorf(\"missing %s discriminator\", discriminator) }\n")
	b.WriteString("\tvar kind string; if err := json.Unmarshal(rawKind, &kind); err != nil || kind == \"\" { return \"\", nil, fmt.Errorf(\"%s discriminator must be a non-empty string\", discriminator) }\n")
	b.WriteString("\treturn kind, append(json.RawMessage(nil), data...), nil\n}\n\n")
	b.WriteString("func requireDiscriminatedUnionFields(data json.RawMessage, union, kind string, fields ...string) error { var object map[string]json.RawMessage; if err := json.Unmarshal(data, &object); err != nil { return err }; for _, field := range fields { if _, ok := object[field]; !ok { return fmt.Errorf(\"%s variant %q is missing required field %q\", union, kind, field) } }; return nil }\n\n")

	names := make([]string, 0, len(unions))
	for name := range unions {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		union := unions[name]
		renderDiscriminatedUnion(&b, union.Name, union.Discriminator, union.Kinds, union.Required)
	}
	return []byte(b.String())
}

func renderDiscriminatedUnion(b *strings.Builder, name, discriminator string, kinds []string, required map[string][]string) {
	fmt.Fprintf(b, "// %sKind identifies a known %s variant.\n", name, name)
	fmt.Fprintf(b, "type %sKind string\n\nconst (\n", name)
	for _, kind := range kinds {
		fmt.Fprintf(b, "\t%sKind%s %sKind = %q\n", name, methodBaseName(kind), name, kind)
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(b, "// %s preserves the complete JSON payload for a discriminated union.\n", name)
	fmt.Fprintf(b, "type %s struct { kind %sKind; raw json.RawMessage }\n\n", name, name)
	fmt.Fprintf(b, "// New%s validates the discriminator and wraps a JSON-marshalable %s value.\n", name, name)
	fmt.Fprintf(b, "func New%s(value any) (%s, error) { data, err := json.Marshal(value); if err != nil { return %s{}, err }; var result %s; err = json.Unmarshal(data, &result); return result, err }\n\n", name, name, name, name)
	fmt.Fprintf(b, "func (value *%s) UnmarshalJSON(data []byte) error { kind, raw, err := decodeDiscriminatedUnion(data, %q); if err != nil { return fmt.Errorf(\"decode %s: %%w\", err) }; switch %sKind(kind) {\n", name, discriminator, name, name)
	for _, kind := range kinds {
		fmt.Fprintf(b, "\tcase %sKind%s:\n", name, methodBaseName(kind))
		fields := required[kind]
		if len(fields) == 0 {
			b.WriteString("\t\t// No required payload fields beyond the discriminator.\n")
			continue
		}
		fmt.Fprintf(b, "\t\tif err := requireDiscriminatedUnionFields(raw, %q, kind", name)
		for _, field := range fields {
			fmt.Fprintf(b, ", %q", field)
		}
		b.WriteString("); err != nil { return err }\n")
	}
	fmt.Fprintf(b, "\t}; value.kind = %sKind(kind); value.raw = raw; return nil }\n\n", name)
	fmt.Fprintf(b, "func (value %s) MarshalJSON() ([]byte, error) { if len(value.raw) == 0 { return []byte(\"null\"), nil }; return append([]byte(nil), value.raw...), nil }\n\n", name)
	fmt.Fprintf(b, "// Kind returns the payload discriminator, including unknown future values.\nfunc (value %s) Kind() %sKind { return value.kind }\n\n", name, name)
	fmt.Fprintf(b, "// RawJSON returns a copy of the complete union payload.\nfunc (value %s) RawJSON() json.RawMessage { return append(json.RawMessage(nil), value.raw...) }\n\n", name)
	fmt.Fprintf(b, "// IsKnown reports whether the discriminator was present in the generation schema.\nfunc (value %s) IsKnown() bool { switch value.kind {\n", name)
	for _, kind := range kinds {
		fmt.Fprintf(b, "\tcase %sKind%s:\n\t\treturn true\n", name, methodBaseName(kind))
	}
	b.WriteString("\tdefault:\n\t\treturn false\n\t}\n}\n\n")
}

func generateRPCStubs(schemaDir, repoRoot, codexCommit string) error {
	defs, err := parseDefinitionNames(schemaDir)
	if err != nil {
		return err
	}

	clientMethods, err := loadMethods(filepath.Join(schemaDir, "ClientRequest.json"))
	if err != nil {
		return err
	}

	serverMethods, err := loadMethods(filepath.Join(schemaDir, "ServerRequest.json"))
	if err != nil {
		return err
	}

	notifications, err := loadNotifications(filepath.Join(schemaDir, "ServerNotification.json"))
	if err != nil {
		return err
	}

	clientRPC, err := buildRPCMethods(clientMethods, defs, clientResponseOverrides())
	if err != nil {
		return err
	}

	serverRPC, err := buildRPCMethods(serverMethods, defs, nil)
	if err != nil {
		return err
	}

	outDir := filepath.Join(repoRoot, "rpc")
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}

	if err := writeGoFile(outDir, "client_requests_gen.go", renderClientRequests(clientRPC, codexCommit)); err != nil {
		return err
	}

	if err := writeGoFile(outDir, "server_requests_gen.go", renderServerRequests(serverRPC, codexCommit)); err != nil {
		return err
	}

	if err := writeGoFile(outDir, "notifications_gen.go", renderNotifications(notifications, codexCommit)); err != nil {
		return err
	}

	return nil
}

func parseDefinitionNames(schemaDir string) (map[string]struct{}, error) {
	files, err := findSchemaFiles(schemaDir)
	if err != nil {
		return nil, err
	}
	defs := make(map[string]struct{})
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return nil, err
		}
		var doc struct {
			Title       string                     `json:"title"`
			Definitions map[string]json.RawMessage `json:"definitions"`
		}
		if err := json.Unmarshal(data, &doc); err != nil {
			return nil, err
		}
		if doc.Title != "" {
			defs[doc.Title] = struct{}{}
		}
		for name := range doc.Definitions {
			defs[name] = struct{}{}
		}
	}
	return defs, nil
}

func schemaTitle(path string) (string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	var doc struct {
		Title string `json:"title"`
	}
	if err := json.Unmarshal(data, &doc); err != nil {
		return "", err
	}
	return doc.Title, nil
}

func writeFallbackTypes(outDir string, titles []string, generated map[string]struct{}, codexCommit string) error {
	fallbackPath := filepath.Join(outDir, "fallback_gen.go")
	if len(titles) == 0 {
		_ = os.Remove(fallbackPath)
		return nil
	}

	unique := map[string]struct{}{}
	for _, title := range titles {
		if title != "" {
			unique[title] = struct{}{}
		}
	}

	aliases := map[string]string{}
	var names []string
	for name := range unique {
		if _, exists := generated[name]; exists {
			continue
		}
		if target, ok := sanitizedFallbackTarget(name, generated); ok {
			aliases[name] = target
			continue
		}
		if _, allowed := opaqueFallbackTypeAllowlist[name]; !allowed {
			return fmt.Errorf("schema %s requires an unreviewed interface{} fallback; add typed generation or an explicit opaque allowlist entry", name)
		}
		names = append(names, name)
	}
	if len(names) == 0 && len(aliases) == 0 {
		_ = os.Remove(fallbackPath)
		return nil
	}
	sort.Strings(names)
	aliasNames := make([]string, 0, len(aliases))
	for name := range aliases {
		aliasNames = append(aliasNames, name)
	}
	sort.Strings(aliasNames)

	var b strings.Builder
	b.WriteString(generatedHeader(codexCommit))
	b.WriteString("package protocol\n\n")
	b.WriteString("// Fallback types for schemas that failed to generate.\n")
	for _, name := range aliasNames {
		b.WriteString("type ")
		b.WriteString(name)
		b.WriteString(" = ")
		b.WriteString(aliases[name])
		b.WriteString("\n")
	}
	for _, name := range names {
		b.WriteString("type ")
		b.WriteString(name)
		b.WriteString(" interface{}\n")
	}

	return writeGoFile(outDir, filepath.Base(fallbackPath), []byte(b.String()))
}

