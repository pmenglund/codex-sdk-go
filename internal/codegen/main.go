func writeFallbackTypes(outDir string, titles []string, generated map[string]struct{}, codexCommit string) error {
	fallbackPath := filepath.Join(outDir, "fallback_gen.go")
	if len(titles) == 0 {
		_ = os.Remove(fallbackPath)
		return nil
	}

	unique := map[string]struct{}{}
	for _, title := range titles {
		if title != "" {
			unique[title] = struct{}{}
		}
	}

	aliases := map[string]string{}
	var names []string
	for name := range unique {
		if _, exists := generated[name]; exists {
			continue
		}
		if target, ok := sanitizedFallbackTarget(name, generated); ok {
			aliases[name] = target
			continue
		}
		if _, allowed := opaqueFallbackTypeAllowlist[name]; !allowed {
			return fmt.Errorf("schema %s requires an unreviewed interface{} fallback; add typed generation or an explicit opaque allowlist entry", name)
		}
		names = append(names, name)
	}
	if len(names) == 0 && len(aliases) == 0 {
		_ = os.Remove(fallbackPath)
		return nil
	}
	sort.Strings(names)
	aliasNames := make([]string, 0, len(aliases))
	for name := range aliases {
		aliasNames = append(aliasNames, name)
	}
	sort.Strings(aliasNames)

	var b strings.Builder
	b.WriteString(generatedHeader(codexCommit))
	b.WriteString("package protocol\n\n")
	b.WriteString("// Fallback types for schemas that failed to generate.\n")
	for _, name := range aliasNames {
		b.WriteString("type ")
		b.WriteString(name)
		b.WriteString(" = ")
		b.WriteString(aliases[name])
		b.WriteString("\n")
	}
	for _, name := range names {
		b.WriteString("type ")
		b.WriteString(name)
		b.WriteString(" interface{}\n")
	}

	return writeProtocolGoFile(outDir, filepath.Base(fallbackPath), []byte(b.String()))
}

